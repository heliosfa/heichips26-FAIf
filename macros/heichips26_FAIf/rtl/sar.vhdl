-- Description:
--
-- This entity implements the Successive Approximation Register (SAR)
-- for a SAR Analogue to Digital Converter (ADC). The block has a
-- low-active asynchronous reset and a high-active synchronous clear
-- for the internal value and mask registers, which have priority over
-- the other sequential behaviour. If the `ena` input is '0', then the
-- internal value and mask registers are not updated at the rising edge
-- of clock. Setting `start` to high for at least a clock cycle, will
-- start the conversion. During the conversion, the `done` output is
-- low. The SAR will start progressively setting/clearing the bits of
-- its internal value register starting from the MSB down to the
-- LSB. That value register constitutes the reference value for the DAC
-- that generates the comparison voltage during conversion. An
-- analogue comparator compares the voltage at the sample & hold
-- output with the reference voltage generated by the DAC. Its output
-- is connected to the `comp` input of the SAR. First, the MSB is set
-- to '1'. At each subsequent clock cycle, the `comp` input is checked
-- and the next bit in direction to LSB is set to '1'. If the `comp`
-- input is '0' then the previous set bit is cleared, i.e., set to
-- '0'. Once the decision for the LSB value is made, the conversion is
-- done and the `tick` output is set to '1' for one clock cycle. The
-- `done` output is always at '1' when the SAR is idle, i.e., no
-- conversion is in progress. The `value` output is also connected to
-- the internal value register, i.e., it shows the conversion in
-- progress.
--
